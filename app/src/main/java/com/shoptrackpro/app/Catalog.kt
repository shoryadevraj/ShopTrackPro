  nameEn=en,nameHi=hi,category=cat,description=desc,brand=brand,defaultUnit=unit,
  aliases=listOf(hinglishNames[en],alias).filterNotNull().filter{it.isNotBlank()}.distinct().joinToString(", ")
 )
